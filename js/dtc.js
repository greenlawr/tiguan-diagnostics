const SYSTEMS = { P: 'Powertrain', C: 'Chassis', B: 'Body', U: 'Network' };

export const hasDescription = (code) => Boolean(CODES[code]);

export function describeDtc(code) {
  if (CODES[code]) return CODES[code];
  const generic = code[1] === '0' || (code[0] === 'P' && code[1] === '2') || (code[0] === 'U' && code[1] === '3');
  return `${SYSTEMS[code[0]] || 'Unknown'} fault, ${generic ? 'generic' : 'Volkswagen-specific'} code (no built-in description)`;
}

export function lookupUrl(code) {
  return 'https://www.google.com/search?q=' + encodeURIComponent(`VW Tiguan ${code} fault code`);
}
